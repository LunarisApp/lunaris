import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { validateManifest } from "../../../packages/plugin-sdk/src/manifest";
import {
	OFFICIAL_MARKETPLACE_MANIFEST_URL,
	parseExtensionMarketplace,
	parsePluginReleaseDescriptor,
} from "../../../packages/plugin-sdk/src/marketplace";

// Build a local catalog from the same validated metadata used by the app.
// Builds and page requests never depend on the marketplace being online.
const root = new URL("../../../", import.meta.url);
const assetRoot = new URL("apps/landing/public/img/extensions/", root);
await mkdir(assetRoot, { recursive: true });

async function download(url: string) {
	const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
	if (!response.ok) throw new Error(`${response.status}: ${url}`);
	return Buffer.from(await response.arrayBuffer());
}

async function saveImage(slug: string, bytes: Buffer, width: number) {
	const filename = `${slug}.webp`;
	const image = await sharp(bytes)
		.resize({ width, withoutEnlargement: true })
		.webp({ quality: 86 })
		.toBuffer({ resolveWithObject: true });
	await writeFile(new URL(filename, assetRoot), image.data);
	return {
		src: `/img/extensions/${filename}`,
		width: image.info.width,
		height: image.info.height,
	};
}

const marketplace = parseExtensionMarketplace(
	JSON.parse((await download(OFFICIAL_MARKETPLACE_MANIFEST_URL)).toString()),
	OFFICIAL_MARKETPLACE_MANIFEST_URL,
);
const entries = [];
for (const entry of marketplace.extensions) {
	const release = entry.versions.find(
		(version) => version.version === entry.latestVersion,
	);
	if (release?.status !== "active") continue;
	const bytes = await download(release.descriptor.url);
	if (
		bytes.length !== release.descriptor.bytes ||
		createHash("sha256").update(bytes).digest("hex") !==
			release.descriptor.sha256
	) {
		throw new Error(`Descriptor integrity mismatch: ${entry.id}`);
	}
	const descriptor = parsePluginReleaseDescriptor(
		JSON.parse(bytes.toString()),
		{ id: entry.id, version: release.version },
		release.descriptor.url,
	);
	const slug = entry.id.replace(/^lunaris\./, "");
	if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`Invalid slug: ${slug}`);
	const iconUrl = entry.iconUrl ?? descriptor.icon?.url;
	if (!iconUrl) throw new Error(`Missing icon: ${entry.id}`);
	const screenshots = [];
	for (const [index, screenshot] of (entry.screenshots ?? []).entries()) {
		screenshots.push({
			...(await saveImage(
				`${slug}-screenshot-${index + 1}`,
				await download(screenshot.url),
				1600,
			)),
			alt: screenshot.alt,
		});
	}
	entries.push({
		slug,
		id: entry.id,
		name: entry.name,
		builtIn: false,
		developer: entry.developer,
		version: release.version,
		api: release.api,
		iconUrl,
		description: entry.description,
		longDescription:
			entry.longDescription ?? descriptor.manifest.longDescription,
		keywords: entry.keywords ?? [],
		permissions: descriptor.manifest.permissions,
		repository: entry.repository,
		website: entry.homepageUrl,
		screenshots,
	});
}
for (const slug of ["rich-text", "kanban", "file"]) {
	const manifest = validateManifest(
		JSON.parse(
			await readFile(
				new URL(`extensions/${slug}/src/manifest.json`, root),
				"utf8",
			),
		),
	);
	const screenshot = await saveImage(
		`${slug}-screenshot-1`,
		await readFile(
			new URL(
				`internal/workspaces/src/features/extensions/assets/${slug}.png`,
				root,
			),
		),
		1600,
	);
	entries.push({
		slug,
		id: manifest.id,
		name: manifest.name,
		builtIn: true,
		developer: manifest.developer,
		version: manifest.version,
		api: manifest.api,
		description: manifest.description,
		longDescription: manifest.longDescription,
		keywords: manifest.keywords ?? [],
		permissions: manifest.permissions,
		repository: `https://github.com/LunarisApp/lunaris/tree/next/extensions/${slug}`,
		website: manifest.website,
		screenshots: [{ ...screenshot, alt: `${manifest.name} in Lunaris` }],
	});
}
entries.sort((a, b) => a.name.localeCompare(b.name, "en"));
const output = `// Generated by bun run extensions:sync. Do not edit by hand.\n// Source: ${OFFICIAL_MARKETPLACE_MANIFEST_URL}\nimport type { CatalogExtension } from "./extension-types";\n\nexport const catalogUpdatedAt = ${JSON.stringify(marketplace.generatedAt)};\nexport const extensionCatalog: readonly CatalogExtension[] = ${JSON.stringify(entries, null, "\t")};\n`;
await writeFile(
	new URL("apps/landing/src/data/extension-catalog.ts", root),
	output,
);
process.stdout.write(
	`Synced ${entries.length} extensions to ${fileURLToPath(assetRoot)}\n`,
);
